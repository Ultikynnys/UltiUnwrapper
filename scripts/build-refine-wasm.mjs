import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = resolve(root, 'wasm/refine/Cargo.toml');
const wasmPath = resolve(
  root,
  'wasm/refine/target/wasm32-unknown-unknown/release/ultiunwrapper_refine.wasm',
);
const output = resolve(root, 'src/lib/unwrap/refineWasmBinary.ts');

execFileSync('cargo', ['build', '--manifest-path', manifest, '--target', 'wasm32-unknown-unknown', '--release'], {
  cwd: root,
  stdio: 'inherit',
});

const bytes = readFileSync(wasmPath);
const base64 = bytes.toString('base64');
const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `/* Generated by scripts/build-refine-wasm.mjs. */\nexport const REFINE_WASM_SHA256 = '${hash}';\nexport const REFINE_WASM_BASE64 = '${base64}';\n`,
);

console.log(`Wrote ${output}`);
console.log(`WASM ${bytes.length} bytes, base64 ${base64.length} characters, sha256 ${hash}`);
